#!/usr/bin/env node
"use strict";

// Builds js/data/openings.data.js (Ludus.OpeningsData) from data/openings/{a,b,c,d,e}.tsv, the Lichess
// "chess-openings" dataset (https://github.com/lichess-org/chess-openings, CC0 / public domain; see
// THIRD_PARTY_NOTICES.md). Every line (eco, name, pgn) is replayed with js/chess.js; an illegal move fails the build.
//
// What is shipped (read by js/openings.js):
//   families   the distinct names before ":" ("Sicilian Defense")
//   names      one line per dataset line: "<eco>\t<family index>\t<the rest of the name, or empty>"
//   positions  every position on a dataset line (the named ends and the moves leading to them), as
//              Openings.keyHash(Openings.positionKey(fen)), followed by ".<name index in base 36>" when the
//              position has a name; separated by spaces. Keyed by the position, so a transposition finds it.
//
// Usage:
//   node scripts/build-openings.js          write the data file
//   node scripts/build-openings.js --check  fail when the committed data file is not what the dataset gives

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const DATA_DIR = path.join(ROOT, "data", "openings");
const OUT_FILE = path.join(ROOT, "js", "data", "openings.data.js");
const FILES = ["a.tsv", "b.tsv", "c.tsv", "d.tsv", "e.tsv"];

require(path.join(ROOT, "js", "ludus.js"));
const { Chess, sanToMove } = require(path.join(ROOT, "js", "chess.js"));
const Openings = require(path.join(ROOT, "js", "openings.js"));

function readLines() {
  const lines = [];
  FILES.forEach((file) => {
    const text = fs.readFileSync(path.join(DATA_DIR, file), "utf8").replace(/\r/g, "");
    text.split("\n").slice(1).forEach((row, index) => {
      if (!row.trim()) return;
      const [eco, name, pgn] = row.split("\t");
      if (!eco || !name || !pgn) throw new Error(`${file}:${index + 2}: expected "eco<TAB>name<TAB>pgn"`);
      lines.push({ eco, name, pgn, where: `${file}:${index + 2}` });
    });
  });
  return lines;
}

function buildData() {
  const lines = readLines();
  const families = [];
  const familyIndex = new Map();
  const names = [];
  // hash -> name index (-1: on a line, no name of its own); and the key behind each hash, to catch a collision.
  const positions = new Map();
  const keyOf = new Map();
  const note = (key, index) => {
    const hash = Openings.keyHash(key);
    const seen = keyOf.get(hash);
    if (seen !== undefined && seen !== key) throw new Error(`hash collision between "${seen}" and "${key}"`);
    keyOf.set(hash, key);
    if (!positions.has(hash) || (positions.get(hash) === -1 && index >= 0)) positions.set(hash, index);
  };
  lines.forEach((line, lineIndex) => {
    const family = Openings.familyOf(line.name);
    if (!familyIndex.has(family)) {
      familyIndex.set(family, families.length);
      families.push(family);
    }
    const rest = line.name.length > family.length ? line.name.slice(family.length).replace(/^\s*:\s*/, "") : "";
    names.push(`${line.eco}\t${familyIndex.get(family)}\t${rest}`);
    const chess = new Chess();
    const sans = line.pgn.replace(/\d+\.(\.\.)?/g, " ").trim().split(/\s+/);
    sans.forEach((san, i) => {
      const move = sanToMove(san, chess);
      if (!move) throw new Error(`${line.where}: illegal move "${san}" in ${line.pgn}`);
      chess.makeMove(move);
      // The named position is the end of the line; the ones before it are book positions without a name of their own
      // (unless another line names them).
      note(Openings.positionKey(chess.fen()), i === sans.length - 1 ? lineIndex : -1);
    });
  });
  const tokens = [];
  positions.forEach((index, hash) => tokens.push(index >= 0 ? `${hash}.${index.toString(36)}` : hash));
  return {
    v: Openings.DATA_VERSION,
    source: "lichess-org/chess-openings (CC0)",
    lines: lines.length,
    families,
    names: names.join("\n"),
    positions: tokens.join(" "),
  };
}

function render(data) {
  return [
    "// GENERATED by scripts/build-openings.js from data/openings/ - do not edit by hand.",
    "// Opening names: the Lichess chess-openings dataset (CC0, public domain), see THIRD_PARTY_NOTICES.md.",
    "(function (root) {",
    "  \"use strict\";",
    "  root.Ludus = root.Ludus || {};",
    `  root.Ludus.OpeningsData = ${JSON.stringify(data)};`,
    "})(typeof globalThis !== \"undefined\" ? globalThis : this);",
    "",
  ].join("\n");
}

if (require.main === module) {
  const body = render(buildData());
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, "utf8") : "";
    if (current !== body) {
      console.error("js/data/openings.data.js is stale: run node scripts/build-openings.js");
      process.exit(1);
    }
    console.log("openings data up to date");
  } else {
    fs.writeFileSync(OUT_FILE, body);
    console.log(`wrote ${path.relative(ROOT, OUT_FILE)} (${body.length} bytes)`);
  }
}

module.exports = { buildData, render, OUT_FILE };
