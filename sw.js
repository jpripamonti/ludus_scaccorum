// The list above is generated by scripts/generate-version.js: every local
// script and stylesheet index.html loads, versioned with the content hash, plus
// the static assets. Do not edit the JS/CSS entries by hand.
//
// The engine is deliberately absent from the list above: it is 7.3 MB and is
// only needed once somebody actually plays. The same goes for lazily loaded
// data (js/data/*.js, fetched with ?v=<version> by Ludus.util.loadScript). The
// fetch handler below stores any successful same-origin GET the first time it
// is requested, so those files are there offline from then on.

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(CORE_ASSETS))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys
        .filter((key) => key !== CACHE_NAME)
        .map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

function sameOriginGet(request) {
  if (request.method !== "GET") return false;
  const url = new URL(request.url);
  return url.origin === self.location.origin;
}

function navigationFallback(request) {
  return fetch(request).catch(() => caches.match("./index.html"));
}

function cacheFirst(request) {
  return caches.match(request)
    .then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (response && response.ok) {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
        }
        return response;
      });
    })
    .catch(() => caches.match(request, { ignoreSearch: true }));
}

self.addEventListener("fetch", (event) => {
  if (!sameOriginGet(event.request)) return;
  if (event.request.mode === "navigate") {
    event.respondWith(navigationFallback(event.request));
    return;
  }
  event.respondWith(cacheFirst(event.request));
});
